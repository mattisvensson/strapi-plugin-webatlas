import type { Route, User } from './'

export type Navigation = {
	id: number
	name: string
	slug: string
	visible: boolean
	items: Route[]
	updatedAt: string
	createdAt: string
}

export type NavigationInput = Omit<Navigation, 'id' | 'items' | 'updatedAt' | 'createdAt' | 'slug'>

export type NavItem = {
	createdAt: string
	createdBy: User
	id: number
	items: Route[]
	name: string
	slug: string
	updatedAt: string
	updatedBy: User
	visible: boolean
}

export type NavItemSettings = {
	route: string | null
	navigation: string | null
	parent: string | null
	order?: number
}

export type NestedNavigation = {
	id: number
	documentId: string
	name: string
	slug: string
	visible: boolean
	// Depth index of the deepest allowed level, 0 = root only
	maxDepth?: number
	items: NestedNavItem[]
	updatedAt: string
	createdAt: string
}

export type NavigationDepth = {
	documentId: string
	name: string
	maxDepth: number
	// Depth index of the deepest existing item, -1 for an empty navigation
	deepestDepth: number
}

export type NestedNavItem = {
	id: number
	documentId: string
	items: NestedNavItem[]
	parent: {
		documentId: string
	} | null
	route: Route
	updatedAt: string
	createdAt: string
	status: 'published' | 'draft' | 'modified' | null
	depth?: number
	order: number
	clientModifications?: ClientModifications
	initialClientModifications?: ClientModifications
}

export type ClientModifications = {
	type: 'create' | 'update' | 'delete'
	title?: string
	slug?: string
	path?: string
	isOverride?: boolean
	route?: string | null
	parent?: string | null
	navigation?: string | null
	autoGenerated?: boolean
}

export type StructuredNavigationVariant = 'nested' | 'flat'
