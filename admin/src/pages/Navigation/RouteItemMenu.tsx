import type { NestedNavItem } from '../../../../types'
import { Typography, SimpleMenu, MenuItem, IconButton } from '@strapi/design-system'
import { More } from '@strapi/icons'
import { getTranslation } from '../../utils'
import { useIntl } from 'react-intl'
import { useHref } from 'react-router-dom'

export default function RouteItemMenu({
	item,
	depth,
	maxDepth,
	handleEdit,
	handleAddChildren,
	handleDelete,
	handleRestore,
	handleUndoDelete,
}: {
	item: NestedNavItem
	depth?: number
	maxDepth: number
	handleEdit: () => void
	handleAddChildren: () => void
	handleDelete: () => void
	handleRestore: () => void
	handleUndoDelete: () => void
}) {
	const { formatMessage } = useIntl()

	const viewEntityTo =
		item.route.relatedContentType && item.route.relatedDocumentId
			? `/content-manager/collection-types/${item.route.relatedContentType}/${item.route.relatedDocumentId}`
			: null
	// Opened in a new tab, so unsaved changes of the navigation are kept
	const viewEntityHref = useHref(viewEntityTo ?? '')
	// Changes made by moving the item are generated automatically and cannot be reset here
	const hasEdits =
		item.clientModifications?.type === 'update' && !item.clientModifications.autoGenerated

	return (
		<SimpleMenu
			label={formatMessage({
				id: getTranslation('navigation.page.navItem.actions'),
				defaultMessage: 'Item actions',
			})}
			tag={IconButton}
			icon={<More />}
		>
			{item.clientModifications?.type === 'delete' && (
				<MenuItem onClick={() => handleUndoDelete()}>
					{formatMessage({
						id: getTranslation('navigation.page.navItem.undoDelete'),
						defaultMessage: 'Undo delete',
					})}
				</MenuItem>
			)}
			{hasEdits && (
				<MenuItem onClick={() => handleRestore()}>
					{formatMessage({
						id: getTranslation('navigation.page.navItem.resetEdits'),
						defaultMessage: 'Reset edits',
					})}
				</MenuItem>
			)}
			{item.clientModifications?.type !== 'delete' && (
				<>
					<MenuItem onClick={() => handleEdit()}>
						{formatMessage({
							id: getTranslation('edit'),
							defaultMessage: 'Edit',
						})}
					</MenuItem>
					{item.route.type === 'internal' && viewEntityTo && (
						<MenuItem isExternal href={viewEntityHref}>
							{formatMessage({
								id: getTranslation('navigation.page.navItem.viewEntity'),
								defaultMessage: 'Open entry',
							})}
						</MenuItem>
					)}
					{depth !== undefined && depth < maxDepth && (
						<MenuItem onClick={() => handleAddChildren()}>
							{formatMessage({
								id: getTranslation('navigation.page.navItem.addChildren'),
								defaultMessage: 'Add children',
							})}
						</MenuItem>
					)}
					<MenuItem onClick={() => handleDelete()}>
						<Typography textColor="danger600">
							{formatMessage({
								id: getTranslation('delete'),
								defaultMessage: 'Delete',
							})}
						</Typography>
					</MenuItem>
				</>
			)}
		</SimpleMenu>
	)
}
