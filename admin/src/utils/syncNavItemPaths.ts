import type { NestedNavItem } from '../../../types'
import findParentNavItem from './findParentNavItem'

/**
 * Returns the path of a navigation item. Internal items are built from the path of their closest
 * internal parent and their own slug, other items keep the path of their route.
 */
export function getNavItemPath(navigationItems: NestedNavItem[], item: NestedNavItem): string {
	if (!item.route) return ''
	if (item.route.type !== 'internal') return item.route.path

	const parentNavItem = findParentNavItem({
		navigationItems,
		targetItem: item,
		onlyInternalItems: true,
	})
	const parentPath = parentNavItem
		? `${parentNavItem.clientModifications?.path || parentNavItem.route.path}/`
		: ''
	const itemSlug = item.clientModifications?.slug || item.route.slug
	return `${parentPath}${itemSlug}`
}

/**
 * Keeps clientModifications.path of all internal items in sync with their computed path.
 * Items are processed in order, so parents are already synced when the path of their children is
 * computed. Returns the given array if nothing changed.
 */
export default function syncNavItemPaths(
	navigationItems: NestedNavItem[],
	initialNavigationItems: NestedNavItem[] | null,
): NestedNavItem[] {
	const initialItemsById = new Map(initialNavigationItems?.map((item) => [item.documentId, item]))
	const syncedItems = [...navigationItems]
	let hasChanges = false

	syncedItems.forEach((item, index) => {
		if (item.route?.type !== 'internal') return

		const itemPath = getNavItemPath(syncedItems, item)
		const initialItem = initialItemsById.get(item.documentId)
		const hasStructureChanges = initialItem
			? initialItem.order !== item.order || initialItem.depth !== item.depth
			: false

		// Drop auto generated modifications once the item is back at its original path
		if (
			item.clientModifications?.autoGenerated &&
			item.route.path === itemPath &&
			!hasStructureChanges
		) {
			const { clientModifications, ...rest } = item
			syncedItems[index] = rest
			hasChanges = true
			return
		}

		const shouldSyncPath =
			item.clientModifications?.path !== itemPath &&
			(item.clientModifications?.type === 'update' || itemPath !== item.route.path)

		if (shouldSyncPath) {
			syncedItems[index] = {
				...item,
				clientModifications: item.clientModifications
					? { ...item.clientModifications, path: itemPath }
					: { type: 'update', path: itemPath, autoGenerated: true },
			}
			hasChanges = true
		}
	})

	return hasChanges ? syncedItems : navigationItems
}
